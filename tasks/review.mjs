import { indexRecord } from './queries.mjs'

const CATEGORY_TITLE = {
  fact_on_page: 'Fact on one page',
  multi_constraint: 'Multi-constraint',
  page_vs_record: 'Page versus record',
  local_and_delivery: 'Local and delivery',
  catalog_query: 'Catalog query',
}

function skuLine(index, code) {
  const sku = index.skus.get(code)
  const style = index.styles.get(sku.style_id)
  const stores = Object.entries(sku.stock_stores).filter(([, count]) => count > 0).map(([id, count]) => `${id} ${count}`)
  return `\`${code}\` ${style.title}, ${sku.color}, ${sku.size}, $${sku.price}, ${sku.stock_online} online${stores.length ? `, stores: ${stores.join(', ')}` : ''}`
}

function valueText(record, key, value) {
  if (key === 'stores_in_stock') {
    return value.length ? value.map((id) => record.stores.find((store) => store.id === id).name).join(', ') : 'none'
  }
  if (Array.isArray(value)) return value.join(', ')
  if (key === 'delivery_cost') return value === 0 ? 'free ($0)' : `$${value}`
  return String(value)
}

export function renderReview(record, faults, tasks) {
  const index = indexRecord(record)
  const lines = [
    '# Task review',
    '',
    'Generated by `bun tasks/build.mjs`. Do not edit by hand. Every expected answer below is the output of a query over the record in `tasks/queries.mjs`.',
    '',
    `Record seed ${record.meta.seed}, fault seed ${faults.seed}. ${record.meta.styles} styles, ${record.meta.skus} SKUs.`,
    '',
    'For each task, check that the prompt asks one clear question, that the expected answer is the only reasonable reading, and that an impossible task really has no answer.',
    '',
  ]
  for (const category of Object.keys(CATEGORY_TITLE)) {
    lines.push(`## ${CATEGORY_TITLE[category]}`, '')
    for (const task of tasks.filter((entry) => entry.category === category)) {
      lines.push(`### ${task.task_id}${task.impossible ? ' (no correct answer)' : ''}`, '')
      lines.push(`> ${task.prompt}`, '')
      lines.push(`Expected status: \`${task.expected.status}\``, '')
      for (const [i, group] of (task.expected.items || []).entries()) {
        const label = task.expected.items.length > 1 ? `Item ${i + 1}` : 'Item'
        if (!group.sku_in.length) {
          lines.push(`${label}: no matching SKU.`, '')
          continue
        }
        lines.push(`${label}, any of:`, '')
        for (const code of group.sku_in.slice(0, 8)) lines.push(`- ${skuLine(index, code)}`)
        if (group.sku_in.length > 8) lines.push(`- and ${group.sku_in.length - 8} more`)
        lines.push('')
      }
      for (const [key, value] of Object.entries(task.expected.values || {})) {
        lines.push(`- \`${key}\`: ${valueText(record, key, value)}`)
      }
      if (task.expected.values) lines.push('')
      if (task.subject?.near_misses) lines.push(`Near misses: ${task.subject.near_misses} SKU(s) match everything except stock.`, '')
      if (task.subject?.absent_title) lines.push(`No style is titled "${task.subject.absent_title}".`, '')
      if (task.faults.length) lines.push(`Realistic faults on this task: ${task.faults.map((id) => `\`${id}\``).join(', ')}`, '')
    }
  }
  return `${lines.join('\n').trimEnd()}\n`
}
